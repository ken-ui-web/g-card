const assert = require('node:assert/strict');
module.exports = ({call,sheets,token,studentToken,email,student,id}) => {
  const read = () => JSON.parse(JSON.stringify(call('gcAdminChristmas_',token).config));
  let config=read();
  assert.equal(config.live,null);
  assert.equal(call('gcChristmasView_',student,false),null);
  assert.equal(call('gcPublicShopConfig_').packs.some((pack)=>pack.eventId),false);
  assert.equal(call('gcBootstrap_',studentToken).cardMaster.some((card)=>card.cardId==='G023'),false);
  assert.throws(()=>call('gcGetChristmas_',studentToken,true),/管理者のみ/);
  assert.throws(()=>call('gcAdminSaveChristmas_',studentToken,{action:'publish'}),/管理者のみ/);
  const knowledge=id(),reflection=id(),section=id(),question=id(),paragraph=id();
  const definition=(testId,title)=>({testId,title,description:'',sections:[{sectionId:section,title:'問題',description:''}],settings:{startAt:'',endAt:'',targetClasses:[],attemptLimit:0,resultRelease:'immediate',resultDetail:'score',pointMultiplier:0},published:true});
  const base={sectionId:section,options:{choices:['A','B']},required:true,shuffleOptions:false,feedbackCorrect:'',feedbackWrong:''};
  call('gcAdminSaveTest_',token,{test:definition(knowledge,'冬の知識'),questions:[{...base,questionId:question,type:'single',text:'選ぶ',answer:'A',points:1}]});
  call('gcAdminSaveTest_',token,{test:definition(reflection,'冬の抱負'),questions:[{...base,questionId:paragraph,type:'paragraph',text:'抱負',answer:null,points:0,options:{}}]});
  let draft={...config.draft,startAt:new Date(Date.now()-3600000).toISOString(),endAt:new Date(Date.now()+3600000).toISOString(),knowledgeTestId:knowledge,reflectionTestId:reflection,cpuWins:1,onlineWins:1,packPrice:1,rarityRates:{N:0,R:0,SR:0,SSR:100},cardPool:['G023']};
  assert.equal(call('gcChristmasActive_', {...draft,published:true},Date.parse(draft.startAt)-1),false);
  assert.equal(call('gcChristmasActive_', {...draft,published:true},Date.parse(draft.startAt)),true);
  assert.equal(call('gcChristmasActive_', {...draft,published:true},Date.parse(draft.endAt)+1),false);
  config=call('gcAdminSaveChristmas_',token,{action:'save',draft,revision:config.revision}).config;
  assert.equal(call('gcChristmasView_',student,false),null,'下書きを生徒に公開しない');
  assert.equal(call('gcGetChristmas_',token,true).event.preview,true);
  assert.throws(()=>call('gcAdminSaveChristmas_',token,{action:'publish',draft:{...draft,rarityRates:{N:0,R:0,SR:0,SSR:90}},revision:config.revision}),/100%/);
  assert.throws(()=>call('gcAdminSaveChristmas_',token,{action:'publish',draft:{...draft,reflectionTestId:knowledge},revision:config.revision}),/異なる/);
  config=call('gcAdminSaveChristmas_',token,{action:'publish',draft,revision:config.revision}).config;
  assert.throws(()=>call('gcAdminSaveChristmas_',token,{action:'pause',revision:'stale'}),/更新/);
  assert.equal(call('gcChristmasView_',student,false).active,true);
  const pack=call('gcPublicShopConfig_').packs.find((pack)=>pack.eventId);
  assert.equal(pack.price,1); assert.equal(pack.imageKey,'christmas');
  const purchase=id(),acquired=call('gcOpenPack_',studentToken,{packId:pack.packId},purchase);
  assert.ok(acquired.acquired.every((card)=>card.cardId==='G023'),'限定パックからサンタパンチが出る');
  assert.equal(call('gcOpenPack_',studentToken,{packId:pack.packId},purchase).gPoint,acquired.gPoint,'再送で再購入しない');
  assert.equal(call('gcPackMaster_').find((item)=>item.packId==='all-cards').cardPool.includes('G023'),false);
  call('gcSubmitTest_',studentToken,{testId:knowledge,answers:{[question]:'B'}},id());
  assert.equal(call('gcChristmasView_',student,false).progress.knowledgeDone,false);
  call('gcSubmitTest_',studentToken,{testId:knowledge,answers:{[question]:'A'}},id());
  assert.throws(()=>call('gcSubmitTest_',studentToken,{testId:reflection,answers:{[paragraph]:'   '}},id()),/未回答/);
  call('gcSubmitTest_',studentToken,{testId:reflection,answers:{[paragraph]:'今年の学びを生かします'}},id());
  assert.equal(sheets.get('TestResponses').rows.at(-1)[4],'','自由記述本文を残さない');
  const cpuId=id();
  call('gcReportBattle_',studentToken,{battleId:cpuId,mode:'cpu',deckMode:'owned',cpuLevel:4,eventId:'christmas-2026',result:'win'});
  call('gcReportBattle_',studentToken,{battleId:cpuId,mode:'cpu',deckMode:'owned',cpuLevel:4,eventId:'christmas-2026',result:'win'});
  assert.equal(call('gcChristmasView_',student,false).progress.cpuWins,1,'同じ勝利で進捗を二重加算しない');
  assert.equal(JSON.parse(call('gcChristmasProgress_',student).values[8]).length,1,'再送を試合IDで照合する');
  assert.equal(call('gcFrames_',student).length,0);
  const match=(battleId)=>[battleId,'owned',student,'uid1',email,'uid2','win','hash','loss','hash',new Date().toISOString()];
  call('gcOnlineAwardOne_',match(id()),0,true);
  assert.equal(call('gcChristmasView_',student,false).progress.onlineWins,0,'不戦勝は特別ミッション対象外');
  const online=match(id());call('gcOnlineAwardOne_',online,0,false);call('gcOnlineAwardOne_',online,0,false);
  assert.equal(call('gcFrames_',student).length,1,'全達成で一度だけフレームを付与');
  assert.equal(call('gcFrames_',student)[0].noticeSeen,false);
  const own=call('gcOwned_',student),equip=own[0];
  call('gcEquipFrame_',studentToken,{frameId:'christmas-2026',ownedId:equip.ownedId});
  assert.equal(call('gcOwned_',student).find((card)=>card.ownedId===equip.ownedId).frameId,'christmas-2026');
  assert.throws(()=>call('gcEquipFrame_',token,{frameId:'christmas-2026',ownedId:equip.ownedId}),/獲得/);
  const teacherCard=call('gcOwned_',email)[0];
  assert.throws(()=>call('gcEquipFrame_',studentToken,{frameId:'christmas-2026',ownedId:teacherCard.ownedId}),/所持/);
  call('gcAckFrame_',studentToken,{frameId:'christmas-2026'});
  assert.equal(call('gcFrames_',student)[0].noticeSeen,true);
  config=call('gcAdminSaveChristmas_',token,{action:'pause',revision:config.revision}).config;
  assert.equal(call('gcPublicShopConfig_').packs.some((item)=>item.eventId),false);
  assert.throws(()=>call('gcOpenPack_',studentToken,{packId:'christmas-2026'},id()),/パック/);
  assert.equal(call('gcFrames_',student).length,1);
  call('gcEquipFrame_',studentToken,{frameId:'christmas-2026',ownedId:own[1].ownedId});
  assert.equal(call('gcOwned_',student).filter((card)=>card.frameId).length,1,'終了後も付け替えできる');
  assert.equal(call('gcBootstrap_',studentToken).cardMaster.some((card)=>card.cardId==='G023'),true,'イベント後も所持カードを使える');
  assert.equal(call('gcChristmasProgress_',student).values[6],true,'公開停止でも達成記録を保持');
  console.log('Christmas: draft/publication, dates, tests, packs, normal wins, idempotent unlock, permanent frame and authorization OK');
};
