// GAS has a synchronous SHA-256 API. Adapt only the protocol's hashing boundary;
// the battle rules and replay remain the same source as the browser.
import ts from 'typescript';
import { build } from 'esbuild';
import { writeFile } from 'node:fs/promises';
import { dirname } from 'node:path';

await build({
  stdin: { contents: "export { deriveView, stateDigest, deckCommit } from './src/online/protocol';", resolveDir: process.cwd(), loader: 'ts' },
  bundle: true, format: 'iife', globalName: 'GC_ONLINE_ENGINE', target: 'es2020', write: false,
  plugins: [{ name: 'gas-synchronous-hash', setup(builder) {
    builder.onLoad({ filter: /[\\/]online[\\/]protocol\.ts$/ }, async ({ path }) => {
      const { readFile } = await import('node:fs/promises');
      const source = (await readFile(path, 'utf8')).replace(/export async function sha256\(value: string\): Promise<string> \{[\s\S]*?\n\}/, `export function sha256(value: string): string {
        return Utilities.computeDigest(Utilities.DigestAlgorithm.SHA_256, value, Utilities.Charset.UTF_8).map((b: number) => ((b + 256) % 256).toString(16).padStart(2, '0')).join('');
      }`);
      const transformed = ts.transpileModule(source, {
        compilerOptions: { target: ts.ScriptTarget.ES2020, module: ts.ModuleKind.ESNext },
        transformers: { before: [(context) => {
          const visit = (node) => {
            if (ts.isAwaitExpression(node)) return ts.visitNode(node.expression, visit);
            if (node.kind === ts.SyntaxKind.AsyncKeyword) return undefined;
            return ts.visitEachChild(node, visit, context);
          };
          return (root) => ts.visitNode(root, visit);
        }] },
      });
      return { contents: transformed.outputText, loader: 'js', resolveDir: dirname(path) };
    });
  } }],
}).then(async (result) => {
  await writeFile('gas/OnlineEngine.gs', '// Generated by npm run build:online-engine. Do not edit; source: src/online/protocol.ts and src/game/battle.ts.\n' + result.outputFiles[0].text);
});
